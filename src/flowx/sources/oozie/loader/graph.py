_START = "::start"
_FAIL_NOTEBOOK = (
    "# Databricks notebook source\n"
    "# Generated by flowx from Oozie kill node {name!r}: reaching it ends the workflow as failed.\n"
    "raise RuntimeError({message!r})\n"
)
_AGENTIC_DECISION_CODE = "_flowx_unresolved({reason!r})"
_AGENTIC_DECISION_IMPORT = (
    "def _flowx_unresolved(reason):\n"
    "    raise NotImplementedError('flowx could not translate this Oozie decision: ' + reason)\n"
)


class OozieGraphError(ValueError):
    """Raised when a workflow's transitions don't form a valid Oozie graph."""


@dataclass(frozen=True, slots=True)
class _Edge:
    task_key: str
    outcome: str | None


_Alternative = tuple[_Edge, ...]


@dataclass(slots=True, kw_only=True)
class TaskKeys:
    """Task keys chosen for every node that becomes a task, decided before translation starts."""

    actions: dict[str, str]
    decisions: dict[str, list[str]]
    kills: dict[str, str]
    ok_gates: dict[str, str] = field(default_factory=dict)
    failure_gates: dict[str, str] = field(default_factory=dict)
    reach_sentinels: dict[str, str] = field(default_factory=dict)


@dataclass(slots=True, kw_only=True)
class TranslatedAction:
    """An action's main task plus any tasks that must run before it (bridges, prepare steps)."""

    main: Activity
    before: list[Activity] = field(default_factory=list)


@dataclass(slots=True, kw_only=True)
class LoweringResult:
    """Everything lowering produced: the tasks in dependency order, plus notes for reports."""

    tasks: list[Activity]
    task_keys: TaskKeys
    agentic_task_keys: set[str] = field(default_factory=set)
    findings: list[dict[str, Any]] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    kill_messages: dict[str, str] = field(default_factory=dict)
    transformations: list[dict[str, str]] = field(default_factory=list)


def _transitions(node: Node) -> list[tuple[str, str]]:
    """Returns ``(target, kind)`` for every transition out of *node*."""
    if isinstance(node, ActionNode):
        return [(node.ok_to, "ok"), (node.error_to, "error")]
    if isinstance(node, DecisionNode):
        return [(case.to, f"case:{index}") for index, case in enumerate(node.cases)] + [(node.default_to, "default")]
    if isinstance(node, ForkNode):
        return [(path, "fork") for path in node.paths]
    if isinstance(node, JoinNode):
        return [(node.to, "join")]
    return []


def _unique_key(base: str, used: set[str]) -> str:
    base = base or "task"
    key = base
    suffix = 2
    while key in used:
        key = f"{base}_{suffix}"
        suffix += 1
    used.add(key)
    return key


def _is_recoverable(workflow: OozieWorkflow, action: ActionNode) -> bool:
    """An action is recoverable when its error path leads somewhere other than a kill node."""
    return not isinstance(workflow.nodes.get(action.error_to), KillNode)


def assign_task_keys(workflow: OozieWorkflow) -> TaskKeys:
    """Chooses stable, unique task keys for actions, decision conditions, kill tasks, and gates (document order)."""
    used: set[str] = set()
    actions: dict[str, str] = {}
    decisions: dict[str, list[str]] = {}
    kills: dict[str, str] = {}
    for name, node in workflow.nodes.items():
        if isinstance(node, ActionNode):
            actions[name] = _unique_key(to_lowercase_key(name), used)
    for name, node in workflow.nodes.items():
        if isinstance(node, DecisionNode):
            base = to_lowercase_key(name) or "decision"
            decisions[name] = [
                _unique_key(base if index == 0 else f"{base}_case_{index + 1}", used)
                for index in range(len(node.cases))
            ]
        elif isinstance(node, KillNode):
            kills[name] = _unique_key(f"{to_lowercase_key(name)}_kill", used)
    ok_gates: dict[str, str] = {}
    failure_gates: dict[str, str] = {}
    reach_sentinels: dict[str, str] = {}
    for name, node in workflow.nodes.items():
        if not isinstance(node, ActionNode) or not _is_recoverable(workflow, node):
            continue
        key = actions[name]
        ok_gates[name] = _unique_key(f"{key}__ok", used)
        if not isinstance(workflow.nodes.get(node.error_to), EndNode):
            failure_gates[name] = _unique_key(f"{key}__failed", used)
        reach_sentinels[name] = _unique_key(f"{key}__reached", used)
    return TaskKeys(
        actions=actions,
        decisions=decisions,
        kills=kills,
        ok_gates=ok_gates,
        failure_gates=failure_gates,
        reach_sentinels=reach_sentinels,
    )


def _reachable_from(nodes: dict[str, Node], node: Node) -> set[str]:
    """Names of every node reachable by following transitions out of *node* (not counting *node* itself)."""
    seen: set[str] = set()
    queue = deque(target for target, _ in _transitions(node))
    while queue:
        name = queue.popleft()
        if name not in seen:
            seen.add(name)
            queue.extend(target for target, _ in _transitions(nodes[name]))
    return seen


def _fork_path_nodes(nodes: dict[str, Node], fork: ForkNode) -> list[set[str]]:
    """For each path of *fork*, the path's start node plus everything reachable from it."""
    return [{start} | _reachable_from(nodes, nodes[start]) for start in fork.paths]


def _check_fork_join_pairs(nodes: dict[str, Node], reachable: set[str]) -> None:
    """Rejects forks and joins that don't pair up one to one, as Oozie's fork/join validation does.

    A fork's join is the nearest join that every one of its paths reaches. Two forks sharing a join, or a join
    whose arrivals aren't each on exactly one path of its fork (``f1 -> (a, f2 -> (b, c))`` with ``a``, ``b``, ``c``
    all going to one join), would otherwise be lowered as if the join waited for something it doesn't.
    """
    fork_of_join: dict[str, str] = {}
    for name in sorted(reachable):
        fork = nodes[name]
        if not isinstance(fork, ForkNode):
            continue
        path_nodes = _fork_path_nodes(nodes, fork)
        if not path_nodes:
            continue
        common_joins = {
            candidate for candidate in set.intersection(*path_nodes) if isinstance(nodes[candidate], JoinNode)
        }
        nearest = {
            join
            for join in common_joins
            if not any(join in _reachable_from(nodes, nodes[other]) for other in common_joins - {join})
        }
        if not nearest:
            continue
        if len(nearest) > 1:
            raise OozieGraphError(f"fork {name!r} paths don't meet at a single join: {', '.join(sorted(nearest))}")
        (join,) = nearest
        if join in fork_of_join:
            raise OozieGraphError(f"join {join!r} is the join of both fork {fork_of_join[join]!r} and fork {name!r}")
        fork_of_join[join] = name
        arrivals = {source for source in reachable for target, _ in _transitions(nodes[source]) if target == join}
        for arrival in sorted(arrivals):
            owners = [index for index, nodes_on_path in enumerate(path_nodes) if arrival in nodes_on_path]
            if len(owners) != 1:
                raise OozieGraphError(
                    f"join {join!r}: {arrival!r} isn't on exactly one path of fork {name!r} (it's on {len(owners)})"
                )


def _validate(workflow: OozieWorkflow) -> tuple[list[str], list[str]]:
    """Checks the graph and returns ``(topological order of reachable nodes, warnings)``."""
    nodes = workflow.nodes
    if workflow.start.to not in nodes:
        raise OozieGraphError(f"<start> transitions to unknown node {workflow.start.to!r}")
    for name, node in nodes.items():
        for target, _ in _transitions(node):
            if target not in nodes:
                raise OozieGraphError(f"node {name!r} transitions to unknown node {target!r}")

    reachable = {workflow.start.to} | _reachable_from(nodes, nodes[workflow.start.to])

    in_degree = {name: 0 for name in reachable}
    for name in reachable:
        for target, _ in _transitions(nodes[name]):
            in_degree[target] += 1
    ready = deque(name for name in nodes if name in reachable and in_degree[name] == 0)
    order: list[str] = []
    while ready:
        name = ready.popleft()
        order.append(name)
        for target, _ in _transitions(nodes[name]):
            in_degree[target] -= 1
            if in_degree[target] == 0:
                ready.append(target)
    if len(order) != len(reachable):
        raise OozieGraphError("workflow transitions form a cycle: " + ", ".join(sorted(reachable - set(order))))

    # One union over every fork, so nested fork/join pairs are judged against all forks, not just the nearest.
    downstream_of_forks: set[str] = set()
    for name in reachable:
        if isinstance(nodes[name], ForkNode):
            downstream_of_forks |= _reachable_from(nodes, nodes[name])
    for name in order:
        if isinstance(nodes[name], JoinNode) and name not in downstream_of_forks:
            raise OozieGraphError(f"join {name!r} has no fork leading to it")
    _check_fork_join_pairs(nodes, reachable)

    warnings = [
        f"node {name!r} can't be reached from <start> and is not migrated" for name in nodes if name not in reachable
    ]
    return order, warnings


class _Lowering:
    """One lowering run: walks nodes in topological order and appends their tasks."""

    def __init__(
        self,
        workflow: OozieWorkflow,
        task_keys: TaskKeys,
        translate_action: Callable[[ActionNode, str], TranslatedAction],
        translate_predicate: Callable[[str], PredicateTranslation],
    ) -> None:
        self.workflow = workflow
        self.nodes = workflow.nodes
        self.keys = task_keys
        self.translate_action = translate_action
        self.translate_predicate = translate_predicate
        self.result = LoweringResult(tasks=[], task_keys=task_keys)
        self.incoming: dict[str, list[tuple[str, str]]] = defaultdict(list)
        self.memo: dict[str, list[_Alternative]] = {}
        self.used_keys: set[str] = set(task_keys.actions.values()) | set(task_keys.kills.values())
        self.used_keys |= {key for keys in task_keys.decisions.values() for key in keys}
        self.used_keys |= set(task_keys.ok_gates.values()) | set(task_keys.failure_gates.values())
        self.used_keys |= set(task_keys.reach_sentinels.values())
        self.gate_count = 0

    def note(self, rule: str, node: str, detail: str = "") -> None:
        self.result.transformations.append({"rule": rule, "node": node, "detail": detail})

    # ----- entry alternatives ----------------------------------------------------------------------------
    def alternatives(self, name: str) -> list[_Alternative]:
        """The OR-ed ways of reaching *name*; each way is an AND-ed tuple of edges (empty tuple = from start)."""
        if name not in self.memo:
            collected: list[_Alternative] = []
            for source, kind in self.incoming[name]:
                for alternative in self.from_source(source, kind):
                    if alternative not in collected:
                        collected.append(alternative)
            self.memo[name] = collected
        return self.memo[name]

    def from_source(self, source: str, kind: str) -> list[_Alternative]:
        """The ways a single transition ``source --kind-->`` can be taken, as task edges."""
        if source == _START:
            return [()]
        node = self.nodes[source]
        if isinstance(node, ActionNode):
            if source in self.keys.ok_gates:
                gate = self.keys.ok_gates[source] if kind == "ok" else self.keys.failure_gates.get(source)
                return [(_Edge(gate, "true"),)] if gate else []
            # error -> kill: the failure already fails the run, so the edge disappears.
            return [(_Edge(self.keys.actions[source], None),)] if kind == "ok" else []
        if isinstance(node, ForkNode):
            return self.alternatives(source)
        if isinstance(node, JoinNode):
            return [self.join_arrival(source)]
        if isinstance(node, DecisionNode):
            conditions = self.keys.decisions[source]
            if kind.startswith("case:"):
                return [(_Edge(conditions[int(kind.split(":", 1)[1])], "true"),)]
            return [(_Edge(conditions[-1], "false"),)] if conditions else self.alternatives(source)
        return []

    def join_arrival(self, join: str) -> _Alternative:
        """The AND, across the join's fork paths, of "this path has arrived".

        A single path can reach the join by several mutually exclusive routes (an action and its error handler, or
        both branches of a decision). Those routes are OR-ed per path first, so the successor runs once every path
        has arrived by whichever route it took.
        """
        path_of_arrival = self.fork_paths_for(join)
        routes_by_path: dict[object, list[_Alternative]] = {}
        for arrival_source, arrival_kind in self.incoming[join]:
            path = path_of_arrival.get(arrival_source, arrival_source)
            routes = routes_by_path.setdefault(path, [])
            for alternative in self.from_source(arrival_source, arrival_kind):
                if alternative not in routes:
                    routes.append(alternative)
        combined: list[_Edge] = []
        for routes in routes_by_path.values():
            for edge in self.collapse(routes, f"{join} path"):
                if edge not in combined:
                    combined.append(edge)
        return tuple(combined)

    def fork_paths_for(self, join: str) -> dict[str, int]:
        """Maps each node that transitions into *join* to the index of the fork path it lies on.

        The matching fork is the one whose every path leads to the join and whose paths each own their arrivals
        (an arrival reachable from two paths means the join belongs to a fork nested inside them). With several
        candidates, the most deeply nested one wins. Returns an empty mapping when no fork matches, in which case
        each arrival is treated as its own path.
        """
        arrivals = {source for source, _ in self.incoming[join]}
        candidates: list[tuple[str, dict[str, int]]] = []
        for name, node in self.nodes.items():
            if not isinstance(node, ForkNode):
                continue
            path_nodes = _fork_path_nodes(self.nodes, node)
            if not all(join in nodes_on_path for nodes_on_path in path_nodes):
                continue
            mapping: dict[str, int] = {}
            for arrival in arrivals:
                owners = [index for index, nodes_on_path in enumerate(path_nodes) if arrival in nodes_on_path]
                if len(owners) != 1:
                    break
                mapping[arrival] = owners[0]
            else:
                candidates.append((name, mapping))
        if not candidates:
            return {}
        innermost_name, innermost_mapping = candidates[0]
        for name, mapping in candidates[1:]:
            if name in _reachable_from(self.nodes, self.nodes[innermost_name]):
                innermost_name, innermost_mapping = name, mapping
        return innermost_mapping

    def collapse(self, alternatives: list[_Alternative], label: str) -> _Alternative:
        """Turns several OR-ed alternatives into one edge by putting a gate in front of them."""
        if len(alternatives) <= 1:
            return alternatives[0] if alternatives else ()
        gate = self.gate(label, alternatives)
        return (_Edge(gate.task_key, "true"),)

    # ----- dependencies ---------------------------------------------------------------------------------
    def dependencies(self, alternatives: list[_Alternative], label: str) -> tuple[list[Dependency] | None, str | None]:
        """Turns entry alternatives into ``(depends_on, run_if)``.

        One alternative is a plain AND. Several alternatives are an OR merge: each single-edge alternative is
        depended on directly, each multi-edge (join) alternative gets a gate in front, and the task runs when
        at least one of them succeeded.
        """
        meaningful = [alternative for alternative in alternatives if alternative]
        if not meaningful:
            return None, None
        if len(meaningful) == 1:
            return [Dependency(task_key=edge.task_key, outcome=edge.outcome) for edge in meaningful[0]], None
        self.note("CF-OR-MERGE", label, f"{len(meaningful)} alternatives")
        dependencies: list[Dependency] = []
        for alternative in meaningful:
            edge = alternative[0] if len(alternative) == 1 else None
            if edge is not None and any(
                (existing.task_key, existing.outcome) == (edge.task_key, edge.outcome) for existing in dependencies
            ):
                continue
            # depends_on can't hold one task key twice, so a second outcome of the same condition (both branches
            # converge here) goes through its own gate.
            if edge is None or any(existing.task_key == edge.task_key for existing in dependencies):
                edge = _Edge(self.gate(label, [alternative]).task_key, "true")
            dependencies.append(Dependency(task_key=edge.task_key, outcome=edge.outcome))
        return dependencies, "AT_LEAST_ONE_SUCCESS"

    def gate(self, label: str, alternatives: list[_Alternative]) -> IfConditionActivity:
        """Appends a no-compute condition task that passes exactly when *alternatives* would let a task run."""
        self.gate_count += 1
        key = _unique_key(f"{to_lowercase_key(label)}_gate_{self.gate_count}", self.used_keys)
        dependencies, run_if = self.dependencies(alternatives, label)
        gate = IfConditionActivity(
            name=f"{label} gate {self.gate_count}",
            task_key=key,
            op="EQUAL_TO",
            left="true",
            right="true",
            depends_on=dependencies,
            run_if=run_if,
            description="flowx gate: passes when the Oozie transition it stands for was taken",
        )
        self.result.tasks.append(gate)
        return gate

    # ----- node lowering ---------------------------------------------------------------------------------
    def lower(self) -> LoweringResult:
        order, warnings = _validate(self.workflow)
        self.result.warnings.extend(warnings)
        self.incoming[self.workflow.start.to].append((_START, "start"))
        for name in order:
            for target, kind in _transitions(self.nodes[name]):
                self.incoming[target].append((name, kind))
        for name in order:
            node = self.nodes[name]
            if isinstance(node, ActionNode):
                self.lower_action(node)
            elif isinstance(node, DecisionNode):
                self.lower_decision(node)
            elif isinstance(node, KillNode):
                self.lower_kill(node)
            elif isinstance(node, (ForkNode, JoinNode)):
                self.note("CF-FORK-JOIN", name)
        return self.result

    def lower_action(self, node: ActionNode) -> None:
        dependencies, run_if = self.dependencies(self.alternatives(node.name), node.name)
        translated = self.translate_action(node, self.keys.actions[node.name])
        main = translated.main
        if translated.before:
            for task in translated.before:
                task.depends_on = list(dependencies) if dependencies else None
                task.run_if = run_if
                self.result.tasks.append(task)
            main.depends_on = [Dependency(task_key=task.task_key) for task in translated.before]
        else:
            main.depends_on, main.run_if = dependencies, run_if
        if node.retry_max:
            main.max_retries = node.retry_max
            # Oozie's default retry-interval is 10 minutes; an explicit 0 means retry immediately.
            interval_minutes = 10 if node.retry_interval_minutes is None else node.retry_interval_minutes
            main.min_retry_interval_millis = interval_minutes * 60_000
            self.note("CF-RETRY", node.name, f"{node.retry_max} retries")
        if dependencies:
            self.note("CF-OK-EDGE", node.name)
        if not _is_recoverable(self.workflow, node):
            self.note("CF-ERROR-KILL", node.name, node.error_to)
        self.result.tasks.append(main)
        if node.name in self.keys.ok_gates:
            self.outcome_gates(node, main, dependencies, run_if)

    def outcome_gates(
        self, node: ActionNode, main: Activity, dependencies: list[Dependency] | None, run_if: str | None
    ) -> None:
        """Splits a recoverable action's result into success/failure gates, plus a reachability sentinel.

        See the measured semantics in the module docstring: these gates are what let a handler run only when this
        action itself failed, and let the run succeed when Oozie would have recovered.
        """
        # Only the "success"/"failed" literals were measured. A TIMEDOUT or CANCELED action makes both gates false
        # (known M1 gap): neither the ok nor the error path runs.
        state = f"{{{{tasks.{main.task_key}.result_state}}}}"
        gates = [(self.keys.ok_gates[node.name], "success")]
        if node.name in self.keys.failure_gates:
            gates.append((self.keys.failure_gates[node.name], "failed"))
            self.note("CF-ERROR-ACTION", node.name, node.error_to)
        else:
            self.note("CF-ERROR-END", node.name, node.error_to)
        for key, expected_state in gates:
            self.result.tasks.append(
                IfConditionActivity(
                    name=f"{node.name} {expected_state}",
                    task_key=key,
                    op="EQUAL_TO",
                    left=state,
                    right=expected_state,
                    depends_on=[Dependency(task_key=main.task_key)],
                    run_if="ALL_DONE",
                    description=f"flowx gate: did Oozie action {node.name!r} end in {expected_state}?",
                )
            )
        if dependencies:
            self.note("CF-UPSTREAM-SENTINEL", node.name)
            self.result.tasks.append(
                IfConditionActivity(
                    name=f"{node.name} reached",
                    task_key=self.keys.reach_sentinels[node.name],
                    op="EQUAL_TO",
                    left="true",
                    right="true",
                    depends_on=list(dependencies),
                    run_if=run_if,
                    description="flowx sentinel: fails the run when this action was skipped because an upstream failed",
                )
            )

    def lower_decision(self, node: DecisionNode) -> None:
        conditions = self.keys.decisions[node.name]
        entry_dependencies, entry_run_if = self.dependencies(self.alternatives(node.name), node.name)
        for index, case in enumerate(node.cases):
            if index == 0:
                dependencies, run_if = entry_dependencies, entry_run_if
            else:
                dependencies, run_if = [Dependency(task_key=conditions[index - 1], outcome="false")], None
            self.result.tasks.extend(self.condition(node, index, case.predicate, dependencies, run_if))
        if node.cases:
            self.note("CF-DECISION-CHAIN", node.name, f"{len(node.cases)} cases")

    def condition(
        self,
        node: DecisionNode,
        index: int,
        predicate: str,
        dependencies: list[Dependency] | None,
        run_if: str | None,
    ) -> list[Activity]:
        """Lowers one decision case into its condition task (preceded by a bridge notebook when needed)."""
        key = self.keys.decisions[node.name][index]
        name = node.name if index == 0 else f"{node.name} case {index + 1}"
        description = f"Oozie decision case: {predicate}"
        translation = self.translate_predicate(predicate)
        if isinstance(translation, NativeCondition):
            self.note("EL-NATIVE-CONDITION", node.name, predicate)
            return [
                IfConditionActivity(
                    name=name,
                    task_key=key,
                    op=translation.op,
                    left=translation.left,
                    right=translation.right,
                    depends_on=dependencies,
                    run_if=run_if,
                    description=description,
                )
            ]
        if isinstance(translation, BridgedCondition):
            self.note("EL-BRIDGE-CONDITION", node.name, predicate)
            code, imports, widget_bindings = (
                translation.code,
                list(translation.imports),
                dict(translation.widget_bindings),
            )
        else:
            reason = translation.reason if isinstance(translation, AgenticCondition) else "predicate translation failed"
            self.note("EL-AGENTIC-CONDITION", node.name, reason)
            self.result.agentic_task_keys.add(key)
            self.result.findings.append(
                {
                    "code": "agentic_decision",
                    "severity": "gap",
                    "message": f"decision {node.name!r} case {index + 1}: {reason}",
                    "details": {"task_key": key, "predicate": predicate},
                }
            )
            code, imports, widget_bindings = (
                _AGENTIC_DECISION_CODE.format(reason=reason),
                [_AGENTIC_DECISION_IMPORT],
                {},
            )
        return self.bridged_condition(name, key, description, code, imports, widget_bindings, dependencies, run_if)

    def bridged_condition(
        self,
        name: str,
        key: str,
        description: str,
        code: str,
        imports: list[str],
        widget_bindings: dict[str, str],
        dependencies: list[Dependency] | None,
        run_if: str | None,
    ) -> list[Activity]:
        """Emits a bridge notebook that computes the predicate, then a condition on the bridge's task value.

        The bridge is an ordinary Oozie-owned notebook task (not ``IfConditionActivity.bridge_notebook_code``), so
        it carries the decision's own dependencies and waits for any upstream value the predicate reads.
        """
        bridge_key = _unique_key(f"{key}_bridge", self.used_keys)
        bridge = NotebookActivity(
            name=f"{name} (bridge)",
            task_key=bridge_key,
            notebook_path=f"notebooks/{bridge_key}.py",
            generated_source=render_bridge_notebook(
                code, imports, list(widget_bindings), "result", title=f"Oozie decision: {name}"
            ),
            base_parameters=widget_bindings or None,
            depends_on=dependencies,
            run_if=run_if,
        )
        condition = IfConditionActivity(
            name=name,
            task_key=key,
            op="EQUAL_TO",
            left=f"{{{{tasks.{bridge_key}.values.result}}}}",
            right="true",
            depends_on=[Dependency(task_key=bridge_key)],
            description=description,
        )
        return [bridge, condition]

    def lower_kill(self, node: KillNode) -> None:
        self.result.kill_messages[node.name] = node.message
        alternatives = self.alternatives(node.name)
        if not alternatives:
            return
        dependencies, run_if = self.dependencies(alternatives, node.name)
        key = self.keys.kills[node.name]
        self.note("CF-KILL-TASK", node.name)
        self.result.tasks.append(
            NotebookActivity(
                name=f"{node.name} (kill)",
                task_key=key,
                notebook_path=f"notebooks/{key}.py",
                generated_source=_FAIL_NOTEBOOK.format(name=node.name, message=node.message or "workflow killed"),
                depends_on=dependencies,
                run_if=run_if,
            )
        )


def lower_workflow(
    workflow: OozieWorkflow,
    *,
    task_keys: TaskKeys,
    translate_action: Callable[[ActionNode, str], TranslatedAction],
    translate_predicate: Callable[[str], PredicateTranslation],
) -> LoweringResult:
    """Lowers *workflow* into tasks; see the module docstring for the rules.

    Raises:
        OozieGraphError: For unknown transition targets, cycles, or a join no fork leads to.
    """
    return _Lowering(workflow, task_keys, translate_action, translate_predicate).lower()
