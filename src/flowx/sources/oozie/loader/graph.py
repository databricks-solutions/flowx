"""Lower an Oozie workflow's transition graph into Lakeflow tasks.

Oozie says *where to go next* (``ok``/``error`` on actions, fork paths, decision cases). Lakeflow says *what
each task waits for* (``depends_on`` plus a ``run_if`` rule). This module works out, for every node, the
combinations of upstream outcomes that lead to it, and turns them into dependencies that make each task run
in exactly the situations Oozie would run it. Decisions are lowered flat (condition tasks plus explicit
``true``/``false`` edges) so merge points can wait for real branch tails.

Error edges rely on Lakeflow behaviour measured on a workspace (``flowx/sources/oozie/lakeflow_run_semantics.json``): a
skipped-because-upstream-failed task counts as failed for ``AT_LEAST_ONE_FAILED``, so an action whose error path
recovers gets explicit ``{{tasks.X.result_state}}`` gates (``ALL_DONE``) that tell its own failure apart from an
upstream one, plus a sentinel that keeps upstream failures failing the run.

Every dependency on a condition task carries a ``"true"``/``"false"`` outcome; no dependency ever carries a
``"Failed"`` outcome.
"""

